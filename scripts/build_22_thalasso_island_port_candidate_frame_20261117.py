#!/usr/bin/env python3
"""Lock eligible thalassochory island geography before physical current comparisons.

Reuse the exact source CSV generated by EuDiS original-source run #43892007427.
Select regions, do not infer ocean effects or island-to-island connectivity.
"""
from __future__ import annotations
import argparse
import csv
import json
from collections import Counter
from pathlib import Path

def read(p):
    with p.open(newline="",encoding="utf-8-sig") as f:return list(csv.DictReader(f))

def must_unique(rows,key):
    d={}
    for r in rows:
        if r[key] in d:raise ValueError(f"Duplicate {key}: {r[key]}")
        d[r[key]]=r
    return d

def main():
    ap=argparse.ArgumentParser()
    for n in ("source-root","regions","ports","flora","out-dir"):
        ap.add_argument("--"+n,required=True,type=Path)
    a=ap.parse_args()
    a.out_dir.mkdir(parents=True,exist_ok=True)
    files=list(a.source_root.rglob("within_region_eudis_native_introduced_pairs.csv"))
    if len(files)!=1:raise ValueError(f"Source artifact requires exactly one paired CSV; found {len(files)}")
    src=read(files[0])
    islands=[r for r in src if r["class"]=="island"]
    if len(islands)!=22:raise ValueError(f"Original EuDiS 22-island matched cohort changed: {len(islands)}")
    diffs=[float(r["native_minus_introduced_thalasso_pp"]) for r in islands]
    if (sum(x>0 for x in diffs),sum(x<0 for x in diffs),sum(x==0 for x in diffs))!=(17,4,1):
        raise ValueError("Original paired source signs do not match validated CI")
    regions=must_unique(read(a.regions),"area_code_l3")
    ports=must_unique(read(a.ports),"area_code_l3")
    flora=must_unique(read(a.flora),"code")
    items=[]
    for r in sorted(islands,key=lambda x:x["code"]):
        c=r["code"]
        if c not in regions or c not in ports:
            raise ValueError(f"No independently frozen same-code geography/port counts for {c}")
        g=regions[c];p=ports[c];v=flora.get(c)
        if g["class"]!="island" or p["geographic_group"]!="island":
            raise ValueError(f"Source code is not an island for all controls: {c}")
        if str(g["level1"])!=str(r["level1"]) or str(p["level1"])!=str(r["level1"]):
            raise ValueError(f"TDWG level1 mismatch: {c}")
        port_n=int(p["WPI_port_count"])
        items.append({
            "WGSRPD3":c,"region_name":g["region_name"],
            "TDWG_level1":r["level1"],
            "is_Europe_level1":int(r["level1"]=="1"),
            "native_EuDiS_matched":int(r["native_matched"]),
            "introduced_EuDiS_matched":int(r["introduced_matched"]),
            "native_thalasso1":int(r["native_trait_1"]),
            "introduced_thalasso1":int(r["introduced_trait_1"]),
            "native_rate_percent":round(float(r["native_fraction"])*100,6),
            "introduced_rate_percent":round(float(r["introduced_fraction"])*100,6),
            "native_minus_introduced_pp":round(float(r["native_minus_introduced_thalasso_pp"]),6),
            "WPI_port_count":port_n,
            "has_WPI_port":int(port_n>0),
            "Q1_host_resources_native":int(g["native"]),
            "Q1_host_resources_added":int(g["added"]),
            "Q1_relative_resource_increase_pct":round(float(g["increase_pct"]),6),
            "WCVP_intro_flora_fraction":round(float(v["intro_flora_fraction"]),6) if v else None,
            "WCVP_total_flora":int(v["total"]) if v else None,
            "WCVP_island_port_controls_available":int(v is not None),
        })
    with (a.out_dir/"original22_thalasso_island_port_host_candidates.csv").open("w",newline="",encoding="utf8") as f:
        w=csv.DictWriter(f,fieldnames=list(items[0]));w.writeheader();w.writerows(items)
    withport=[x for x in items if x["has_WPI_port"]]
    outside=[x for x in items if x["TDWG_level1"]!="1"]
    good=[x for x in outside if x["WPI_port_count"]>0 and x["native_thalasso1"]>0]
    audit={
      "status":"ORIGINAL_22_SOURCE_ELIGIBLE_REGION_JOIN_NOT_CURRENT_DISPERSAL_RESULT",
      "source_run":43892007427,"original_paired_island_regions":22,
      "paired_signs":{"native_higher":17,"introduced_higher":4,"tie":1},
      "same_WGSRPD3_id_joined":len(items),
      "regions_with_any_WPI_port":len(withport),
      "regions_with_WCVP_port_flora":sum(x["WCVP_island_port_controls_available"] for x in items),
      "Europe_TDWG1_regions":sum(x["is_Europe_level1"] for x in items),
      "outside_Europe_regions":len(outside),
      "outside_Europe_with_WPI_port_and_at_least_one_native_thalasso":len(good),
      "candidate_regions_outside_Europe":[{"code":x["WGSRPD3"],
         "name":x["region_name"],"ports":x["WPI_port_count"],
         "native_thalasso":x["native_thalasso1"],
         "introduced_thalasso":x["introduced_thalasso1"]} for x in good],
      "limits":[
         "WPI port count is modern port inventory, not historical shipping OD.",
         "EuDiS trait is European-source biased morphological dispersal syndrome.",
         "WGSRPD3 geographical units include archipelago/complex regions, not exact seed-source sites.",
         "WCVP is contemporary and Q1 candidate host opportunity is not a dated plant introduction.",
         "No plant-dispersal event, shipping route, current trajectory or butterfly arrival modeled."
      ]
    }
    (a.out_dir/"source22_candidate_join_audit.json").write_text(json.dumps(audit,ensure_ascii=False,indent=2)+"\n")
    print("SOURCE22_OCEAN_PORT_CANDIDATE_GATE",json.dumps(audit,ensure_ascii=False),flush=True)

if __name__=="__main__":main()
